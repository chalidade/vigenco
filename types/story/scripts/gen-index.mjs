// Writes src/stories/index.ts from every folder in src/stories/ that has index.ts + story.json.
// Run before studio/render/still, so adding a story never means editing a shared file.
import fs from "node:fs";
const dir = "src/stories";
const ids = fs.readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(`${dir}/${d.name}/index.ts`) && fs.existsSync(`${dir}/${d.name}/story.json`))
  .map((d) => d.name).sort();
const v = (id) => "s_" + id.replace(/[^a-zA-Z0-9]/g, "_");
fs.writeFileSync(`${dir}/index.ts`,
  `// Generated by scripts/gen-index.mjs. Do not edit.\nimport type { StoryEntry } from "../lib/Story";\n` +
  ids.map((id) => `import ${v(id)} from "./${id}";`).join("\n") +
  `\n\nexport const stories: StoryEntry[] = [${ids.map(v).join(", ")}];\n`);
console.log(`stories: ${ids.join(", ") || "(none)"}`);
